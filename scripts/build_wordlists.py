# -*- coding: utf-8 -*-
"""Build the assets/mrdict/dict_*.txt wordlists from public sources.

The wordlist data is not committed: it is large, and it comes from other
projects. This script rebuilds it from copies you download yourself.

Sources
-------
dict_zh.txt   chinese-xinhua (MIT), characters + idioms + words
dict_cn.txt   the curated word tables in dict_src/words_*.py, DATA = [(word, def)]
dict_big.txt  ECDICT (MIT), filtered and ranked so common words come first;
              optional COCA / Google-20k frequency lists narrow it further

Output is one entry per line, word<TAB>definition, UTF-8, '#' starts a comment.
The engine loads dict_zh, then dict_cn, then dict_big, and the first definition
seen for a word wins.

Examples
--------
    python build_wordlists.py --zh-dir path/to/chinese-xinhua/data --out ../assets
    python build_wordlists.py --ecdict path/to/stardict-ecdict-2.4.2.idx --out ../assets
    python build_wordlists.py --cn-dir path/to/dict_src --out ../assets
"""

from __future__ import print_function

import argparse
import io
import json
import os
import re
import struct
import sys

try:
    _stdout_keepalive = sys.stdout  # keep a reference: the wrapper owns the buffer
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
except Exception:
    pass

HEADER_BIG = '# ECDICT (MIT License, github.com/skywind3000/ECDICT) + frequency subset\n'

# tunables for the ECDICT subset
RANK_LIMIT = 150000      # keep entries whose ECDICT frequency rank is <= this
MAX_DEF_CHARS = 220      # truncate a long definition
MAX_LINES = 6            # at most this many senses per word

FREQ_MARKER = re.compile(u'^(\\([A-Za-z0-9\\-\\/雅托中考高\\s]{0,16}\\))$')
PHONETIC = re.compile(r'^\*\[([^\]]*)\]')
NUMBERS = re.compile(r'\d+')
INFLECTION = re.compile(u'(的过去式|的过去分词|的复数形式|的第三人称单数|的现在分词)')


def build_cn(cn_dir, out_dir):
    """Merge the curated word tables (words_*.py: DATA = [(word, definition), ...])."""
    try:
        sys.path.insert(0, os.path.abspath(cn_dir))
        import words_ac, words_dh, words_ip, words_qz
    except ImportError as exc:
        raise SystemExit('cannot import the word tables from %s (%s); '
                         'point --cn-dir at the folder holding words_*.py' % (cn_dir, exc))

    seen = set()
    rows = []
    dups = 0
    for mod in (words_ac, words_dh, words_ip, words_qz):
        table = getattr(mod, 'DATA', None)
        if table is None:
            print('  ! %s has no DATA table, skipped' % mod.__name__)
            continue
        n = 0
        for word, definition in table:
            key = word.strip().lower()
            if not key or not definition.strip():
                continue
            if key in seen:
                dups += 1
                continue
            seen.add(key)
            rows.append((key, word.strip(), definition.strip()))
            n += 1
        print('  + %-12s %6d entries' % (mod.__name__, n))

    rows.sort(key=lambda r: r[0])
    path = os.path.join(out_dir, 'dict_cn.txt')
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('# curated English-Chinese entries, generated by scripts/build_wordlists.py\n')
        fh.write('# format: word<TAB>definition  (lowercase, sorted; first definition wins)\n')
        for key, word, definition in rows:
            fh.write('%s\t%s\n' % (word, definition))
    print('dict_cn.txt: %d entries (%d duplicates skipped), %d bytes'
          % (len(rows), dups, os.path.getsize(path)))


def build_zh(data_dir, out_dir):
    """Build dict_zh.txt (hanzi + idioms + words) from chinese-xinhua's data/ dir."""
    entries = {}

    def add(word, definition):
        word = (word or '').strip()
        definition = re.sub(r'\s+', ' ', definition or '').strip()
        if not word or len(definition) < 2 or len(word) > 30:
            return False
        if word in entries and len(entries[word]) >= len(definition):
            return False
        entries[word] = definition[:230]
        return True

    def load_json(name):
        path = os.path.join(data_dir, name)
        if not os.path.isfile(path):
            print('  ! missing %s' % path)
            return []
        with open(path, encoding='utf-8') as fh:
            return json.load(fh)

    # single characters: word.json
    hanzi = load_json('word.json')
    for e in hanzi:
        head = '[' + (e.get('pinyin') or '')
        if e.get('radicals'):
            head += '\u00b7' + e['radicals']
        if e.get('strokes'):
            head += '\u00b7' + str(e['strokes']) + u'\u753b'
        head += '] '
        add(e.get('word'), head + (e.get('explanation') or ''))
    print('  + word.json   %6d characters' % len(hanzi))

    # idioms: idiom.json
    idioms = load_json('idiom.json')
    for e in idioms:
        pinyin = e.get('pinyin') or ''
        add(e.get('word'), ('[' + pinyin + '] ' if pinyin else '') + (e.get('explanation') or ''))
    print('  + idiom.json  %6d idioms' % len(idioms))

    # words: ci.json
    words = load_json('ci.json')
    added = 0
    for e in words:
        if isinstance(e, dict) and add(e.get('ci'), (e.get('explanation') or '')[:120]):
            added += 1
    print('  + ci.json     %6d words' % added)

    path = os.path.join(out_dir, 'dict_zh.txt')
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(u'# Chinese entries: characters + idioms + words (chinese-xinhua, MIT)\n')
        for word in sorted(entries):
            fh.write('%s\t%s\n' % (word, entries[word]))
    print('dict_zh.txt: %d entries, %d bytes' % (len(entries), os.path.getsize(path)))


def load_curated(path):
    """Head words already covered by dict_cn.txt, so ECDICT does not shadow them."""
    keys = set()
    if not os.path.isfile(path):
        return keys
    with open(path, encoding='utf-8') as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith('#'):
                cut = line.find('\t')
                if cut > 0:
                    keys.add(line[:cut].strip().lower())
    return keys


def load_freq(paths):
    """Plain one-word-per-line frequency lists (COCA 60k uses a TSV, col 6)."""
    words = set()
    for path in paths:
        if not os.path.isfile(path):
            print('  ! frequency list not found: %s' % path)
            continue
        with open(path, encoding='utf-8', errors='replace') as fh:
            for line in fh:
                line = line.rstrip('\n')
                if not line or line.startswith('#'):
                    continue
                parts = line.split('\t')
                if len(parts) >= 6 and parts[0] == 'lemRank':      # COCA header
                    continue
                word = (parts[5] if len(parts) >= 6 else parts[0]).strip().lower()
                if word and word.isascii() and len(word) <= 32 and \
                        all(ch.isalpha() or ch in ' -' for ch in word):
                    words.add(word)
        print('  + %-24s %6d words' % (os.path.basename(path), len(words)))
    return words


def build_big(idx_path, dict_path, curated, freq, out_dir):
    """Filter ECDICT down to a ranked, size-bounded subset."""
    if not os.path.isfile(idx_path) or not os.path.isfile(dict_path):
        raise SystemExit('need both the .idx and the .dict file of the stardict ECDICT')

    index = open(idx_path, 'rb').read()
    data = open(dict_path, 'rb')
    kept = {}
    seen = ranked = 0
    pos = 0
    while pos < len(index):
        end = index.index(b'\x00', pos)
        raw_word = index[pos:end]
        pos = end + 1
        offset, size = struct.unpack_from('>II', index, pos)
        pos += 8
        seen += 1
        try:
            word = raw_word.decode('utf-8').strip().lower()
        except UnicodeDecodeError:
            continue
        if not word or len(word) > 32 or len(raw_word) != len(word.encode('utf-8')):
            continue
        if word in curated or word in kept:
            continue
        if not all(ch.isascii() and (ch.isalpha() or ch in "'- ") for ch in word):
            continue

        data.seek(offset)
        raw = data.read(size).decode('utf-8', 'replace')
        lines = [l.strip() for l in raw.replace('\r\n', '\n').split('\n') if l.strip()]
        if not lines:
            continue

        rank = None
        rest = []
        for line in lines:
            if FREQ_MARKER.match(line):
                nums = [int(x) for x in NUMBERS.findall(line)]
                if nums:
                    rank = min(nums) if rank is None else min(rank, min(nums))
                continue
            rest.append(line)
        if word not in freq and (rank is None or rank > RANK_LIMIT):
            continue
        ranked += 1

        phonetic = ''
        if rest and rest[0].startswith('*['):
            match = PHONETIC.match(rest[0])
            if match:
                phonetic = match.group(1).strip()
            rest = rest[1:]

        senses = []
        for line in rest:
            if FREQ_MARKER.match(line) or INFLECTION.search(line):
                continue
            senses.append(line)
            if len(senses) >= MAX_LINES:
                break
        if not senses and not phonetic:
            continue

        definition = '; '.join(senses)
        if phonetic:
            definition = '[%s] %s' % (phonetic, definition)
        definition = definition[:MAX_DEF_CHARS].strip()
        if len(definition) < 2:
            continue
        kept[word] = definition

    data.close()
    print('  ECDICT scanned: %d, accepted: %d, kept: %d' % (seen, ranked, len(kept)))

    path = os.path.join(out_dir, 'dict_big.txt')
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(HEADER_BIG)
        for word in sorted(kept):
            fh.write('%s\t%s\n' % (word, kept[word]))
    print('dict_big.txt: %d entries, %d bytes' % (len(kept), os.path.getsize(path)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--out', default='assets', help='output dir (default: ./assets)')
    ap.add_argument('--cn-dir', default='', help='folder with words_*.py curated tables')
    ap.add_argument('--zh-dir', default='', help='chinese-xinhua data/ folder (word/idiom/ci json)')
    ap.add_argument('--ecdict', default='', help='stardict ECDICT .idx file')
    ap.add_argument('--ecdict-dict', default='', help='stardict ECDICT .dict file (default: sibling of --ecdict)')
    ap.add_argument('--freq', nargs='*', default=[], help='frequency list files (plain or COCA tsv)')
    args = ap.parse_args()

    out_dir = os.path.abspath(args.out)
    if not os.path.isdir(out_dir):
        os.makedirs(out_dir)

    if args.cn_dir:
        print('building dict_cn.txt')
        build_cn(args.cn_dir, out_dir)

    if args.zh_dir:
        print('building dict_zh.txt')
        build_zh(args.zh_dir, out_dir)

    if args.ecdict:
        dict_path = args.ecdict_dict or os.path.splitext(args.ecdict)[0] + '.dict'
        print('building dict_big.txt')
        curated = load_curated(os.path.join(out_dir, 'dict_cn.txt'))
        freq = load_freq(args.freq)
        print('  curated head words to protect: %d, frequency words: %d' % (len(curated), len(freq)))
        build_big(args.ecdict, dict_path, curated, freq, out_dir)

    if not (args.cn_dir or args.zh_dir or args.ecdict):
        ap.print_help()


if __name__ == '__main__':
    main()
